export const TILE = 32;

export type Cell = '#' | '%' | '.' | 'S' | '*' | 'G' | 'R' | 'V' | 'C' | 'D';

export interface LevelData {
  width: number;
  height: number;
  /** true = 实心 */
  solid: boolean[][];
  /** 决定用哪套 blob 图块 */
  terrain: (('metal' | 'rock') | null)[][];
  spawn: { x: number; y: number };
  checkpoints: { x: number; y: number }[];
  gate: { x: number; y: number }[];
  relays: { x: number; y: number }[];
  vents: { x: number; y: number }[];
  conduits: { x: number; y: number }[];
  drones: { x: number; y: number }[];
}

const center = (cx: number, cy: number) => ({ x: cx * TILE + TILE / 2, y: cy * TILE + TILE / 2 });

export function parseLevel(raw: string[]): LevelData {
  const height = raw.length;
  const width = raw[0].length;

  const solid: boolean[][] = [];
  const terrain: (('metal' | 'rock') | null)[][] = [];
  const data: LevelData = {
    width, height, solid, terrain,
    spawn: center(6, 28),
    checkpoints: [], gate: [], relays: [], vents: [], conduits: [], drones: [],
  };

  for (let y = 0; y < height; y++) {
    solid[y] = [];
    terrain[y] = [];
    for (let x = 0; x < width; x++) {
      const c = raw[y][x] as Cell;
      const isMetal = c === '#';
      const isRock = c === '%';
      // 闸门格关闭时也算实心，但由闸门对象自己管理，地形层留空
      solid[y][x] = isMetal || isRock;
      terrain[y][x] = isMetal ? 'metal' : isRock ? 'rock' : null;

      switch (c) {
        case 'S': data.spawn = center(x, y); break;
        case '*': data.checkpoints.push(center(x, y)); break;
        case 'G': data.gate.push({ x, y }); break;
        case 'R': data.relays.push(center(x, y)); break;
        case 'V': data.vents.push(center(x, y)); break;
        case 'C': data.conduits.push(center(x, y)); break;
        case 'D': data.drones.push(center(x, y)); break;
        default: break;
      }
    }
  }
  return data;
}
